#!/usr/bin/env python3
"""Nested-day evaluation of cross-day residual corrections for BWSC2025.

Every residual label used to train an outer fold is generated by a physical
base model that excludes both the outer test day and that residual's own day.
The held-out day is never used to fit the base model or residual correction.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data/processed/race_days_distance_geo_weather.csv"
REPLAY = ROOT / "data/processed/full_race_component_replay_5s.csv"
SEGMENTS = ROOT / "data/processed/vehicle_energy_segments_10km.csv"
OUT = ROOT / "reports/residual_crossday_oof.csv"
OUT_SUMMARY = ROOT / "reports/residual_crossday_summary.json"
OUT_REPORT = ROOT / "reports/residual_crossday_report.md"
sys.path.insert(0, str(ROOT / "scripts"))
import fit_vehicle_power_model as vehicle_features  # noqa: E402
import fit_vehicle_energy_segments as segment_fit  # noqa: E402

CAP_W = 100.0
MIN_ROWS = 20
FEATURES = ["speed_kmh", "relative_air_speed_mps", "grade_pct", "temperature_c", "air_density_kgm3"]


def metrics(frame: pd.DataFrame, col: str) -> dict:
    e = frame.measured_w.to_numpy(float) - frame[col].to_numpy(float)
    return {"n_blocks": int(len(e)), "mae_w": float(np.mean(np.abs(e))),
            "p90_abs_error_w": float(np.quantile(np.abs(e), .9)), "bias_w": float(np.mean(e))}


def fit_predict_blocks(d: pd.DataFrame, segments: pd.DataFrame, mask: pd.DataFrame,
                       label_day: int, base_train_days: list[int]) -> pd.DataFrame:
    train_segments = segments[segments.day.isin(base_train_days)].copy()
    stopped = d[(d.day.isin(base_train_days)) & d["Speed[kmh]"].eq(0)
                & d.event_phase.isin(["road_day", "charge"]) & d.measured_w.between(0, 250)].measured_w
    if train_segments.empty or stopped.empty:
        return pd.DataFrame()
    train_segments.attrs["p_aux_w"] = float(stopped.median())
    model = segment_fit.fit_mle(train_segments)["parameters"]
    rows = d[d.day.eq(label_day)].copy()
    rows = rows.merge(mask[mask.day.eq(label_day)], on=["day", "timestamp_utc"], how="left", validate="one_to_one")
    rows["eligible"] = rows.road_model_comparison_eligible.fillna(False).astype(bool)
    rows["predicted_w"] = (model["p_aux_w"] + model["beta_roll"] * rows.roll_basis_w
                           + model["beta_aero"] * rows.aero_basis_w
                           + model["beta_grade"] * rows.grade_basis_w)
    rows = rows[rows.eligible & rows[["measured_w", "predicted_w", "timestamp_utc"]].notna().all(axis=1)].copy()
    rows["block_start_utc"] = rows.timestamp_utc.dt.floor("5min")
    blocks = (rows.groupby(["day", "block_start_utc"], as_index=False)
              .agg(measured_w=("measured_w", "mean"), predicted_w=("predicted_w", "mean"),
                   residual_w=("measured_w", lambda x: np.nan), eligible_rows=("measured_w", "size"),
                   speed_kmh=("Speed[kmh]", "mean"), relative_air_speed_mps=("relative_air_speed_mps", "mean"),
                   grade_pct=("route_grade_smoothed_pct", "mean"), temperature_c=("temperature_2m", "mean"),
                   air_density_kgm3=("air_density_kgm3", "mean"), distance_m=("distance_from_darwin_m", "mean")))
    blocks["residual_w"] = blocks.measured_w - blocks.predicted_w
    return blocks[blocks.eligible_rows.ge(MIN_ROWS)].copy()


def fit_ridge(train: pd.DataFrame, test: pd.DataFrame, alpha: float) -> np.ndarray:
    # Equal total weight per training day prevents long telemetry days dominating.
    day_n = train.groupby("day").size().to_dict()
    w = np.array([1.0 / day_n[int(day)] for day in train.day], dtype=float)
    w *= len(day_n) / w.sum()
    x = train[FEATURES].to_numpy(float)
    xt = test[FEATURES].to_numpy(float)
    mu = np.average(x, axis=0, weights=w)
    var = np.average((x - mu) ** 2, axis=0, weights=w)
    scale = np.sqrt(var)
    scale[scale < 1e-9] = 1.0
    z = (x - mu) / scale
    zt = (xt - mu) / scale
    y = train.residual_w.to_numpy(float)
    intercept = float(np.average(y, weights=w))
    yc = y - intercept
    beta = np.linalg.solve(z.T @ (w[:, None] * z) + alpha * np.eye(z.shape[1]), z.T @ (w * yc))
    return np.clip(intercept + zt @ beta, -CAP_W, CAP_W)


def fit_gp(train: pd.DataFrame, test: pd.DataFrame, noise_sd_w: float) -> tuple[np.ndarray, np.ndarray]:
    """Small fixed-hyperparameter RBF GP; day-balanced noise weights avoid day-size dominance."""
    x = train[FEATURES].to_numpy(float)
    xt = test[FEATURES].to_numpy(float)
    day_n = train.groupby("day").size().to_dict()
    sample_noise = np.array([noise_sd_w**2 * day_n[int(day)] / np.mean(list(day_n.values()))
                             for day in train.day], dtype=float)
    weight = 1.0 / sample_noise
    y = train.residual_w.to_numpy(float)
    mean = float(np.average(y, weights=weight))
    y0 = y - mean
    mu = np.average(x, axis=0, weights=weight)
    scale = np.sqrt(np.average((x - mu) ** 2, axis=0, weights=weight))
    scale[scale < 1e-9] = 1.0
    z, zt = (x - mu) / scale, (xt - mu) / scale
    # A deliberately smooth 5D RBF residual prior; no hyperparameter search on test days.
    length_scale, signal_sd_w = 1.5, 60.0
    d2 = ((z[:, None, :] - z[None, :, :]) ** 2).sum(axis=2)
    k = signal_sd_w**2 * np.exp(-0.5 * d2 / length_scale**2)
    k.flat[::len(k) + 1] += sample_noise
    cross_d2 = ((zt[:, None, :] - z[None, :, :]) ** 2).sum(axis=2)
    cross = signal_sd_w**2 * np.exp(-0.5 * cross_d2 / length_scale**2)
    solved_y = np.linalg.solve(k, y0)
    solved_cross = np.linalg.solve(k, cross.T)
    pred = mean + cross @ solved_y
    # Approximate future-observation uncertainty; day-level shifts remain a limitation.
    var = signal_sd_w**2 - np.einsum("ij,ji->i", cross, solved_cross) + noise_sd_w**2
    return np.clip(pred, -CAP_W, CAP_W), np.sqrt(np.maximum(var, 1.0))


def main() -> None:
    cols = ["day", "timestamp_utc", "timestamp_local", "event_phase", "event_flags", "Solar_Watt[W]",
            "Battery_Watt[W]", "Speed[kmh]", "distance_from_darwin_m", "distance_anchor_confidence",
            "route_elevation_dem_m", "route_grade_smoothed_pct", "temperature_2m", "surface_pressure",
            "wind_speed_10m", "wind_direction_10m"]
    d = pd.read_csv(RAW, usecols=lambda c: c in cols, low_memory=False)
    d["timestamp_utc"] = pd.to_datetime(d.timestamp_utc, utc=True, errors="coerce")
    d = vehicle_features.make_features(d)
    d["measured_w"] = pd.to_numeric(d["Solar_Watt[W]"], errors="coerce") + pd.to_numeric(d["Battery_Watt[W]"], errors="coerce")
    # Reuse physically derived terms from the fitted-model input table, keyed by day/10 km segment;
    # at row-level predictions use the same road-load basis as the online-residual analysis.
    d["roll_basis_w"] = vehicle_features.MASS_NOMINAL_KG * vehicle_features.G * vehicle_features.CRR_NOMINAL * np.cos(np.arctan(d.grade_fraction)) * d.speed_mps
    d["grade_basis_w"] = vehicle_features.MASS_NOMINAL_KG * vehicle_features.G * np.sin(np.arctan(d.grade_fraction)) * d.speed_mps
    segments = pd.read_csv(SEGMENTS)
    mask = pd.read_csv(REPLAY, usecols=["day", "timestamp_utc", "road_model_comparison_eligible"])
    mask["timestamp_utc"] = pd.to_datetime(mask.timestamp_utc, utc=True, errors="coerce")
    mask["road_model_comparison_eligible"] = mask.road_model_comparison_eligible.astype(str).str.lower().eq("true")
    outputs: list[pd.DataFrame] = []
    clean_days = [1, 2, 3, 4, 5]
    for test_day in clean_days:
        training_days = [day for day in clean_days if day != test_day]
        test = fit_predict_blocks(d, segments, mask, test_day, training_days)
        if test.empty:
            continue
        labels = []
        for label_day in training_days:
            base_days = [day for day in clean_days if day not in {test_day, label_day}]
            labels.append(fit_predict_blocks(d, segments, mask, label_day, base_days))
        train = pd.concat(labels, ignore_index=True)
        test = test.copy()
        test["baseline_error_w"] = test.residual_w
        test["baseline_prediction_w"] = test.predicted_w
        train_mean = float(train.groupby("day").residual_w.mean().mean())
        models: dict[str, np.ndarray] = {
            "crossday_bias": np.full(len(test), np.clip(train_mean, -CAP_W, CAP_W)),
            "ridge_a1": fit_ridge(train, test, 1.0),
            "ridge_a10": fit_ridge(train, test, 10.0),
        }
        gp_spreads: dict[str, np.ndarray] = {}
        for noise_sd in [60.0, 100.0]:
            key = f"gpr_rbf_noise{int(noise_sd)}"
            models[key], gp_spreads[key] = fit_gp(train, test, noise_sd)
        # A route-distance lookup is included only as a 2025-course-specific diagnostic.
        train["route_bin_10km"] = (train.distance_m // 10000).astype("Int64")
        test["route_bin_10km"] = (test.distance_m // 10000).astype("Int64")
        lookup = train.groupby("route_bin_10km").residual_w.agg(["median", "count"])
        route_corr = test.route_bin_10km.map(lookup["median"]).fillna(0.0).to_numpy(float)
        route_n = test.route_bin_10km.map(lookup["count"]).fillna(0.0).to_numpy(float)
        # Require labels from at least two clean training days in a route bin; shrink sparse bins.
        day_counts = train.groupby("route_bin_10km").day.nunique()
        distinct = test.route_bin_10km.map(day_counts).fillna(0).to_numpy(float)
        route_corr = np.where(distinct >= 2, route_corr * distinct / (distinct + 2.0), 0.0)
        models["route_10km_diagnostic"] = np.clip(route_corr, -CAP_W, CAP_W)
        for name, correction in models.items():
            test[f"{name}_correction_w"] = correction
            test[f"{name}_prediction_w"] = test.predicted_w + correction
            if name in gp_spreads:
                test[f"{name}_predictive_sd_w"] = gp_spreads[name]
        test["fold_train_days"] = ",".join(map(str, training_days))
        test["label_crossfit"] = "each training-day label base fit excludes the outer test day and that label day"
        outputs.append(test)
    oof = pd.concat(outputs, ignore_index=True)
    method_cols = ["crossday_bias", "ridge_a1", "ridge_a10", "gpr_rbf_noise60",
                   "gpr_rbf_noise100", "route_10km_diagnostic"]
    rows = []
    for method in method_cols:
        pred_col = f"{method}_prediction_w"
        for day, g in oof.groupby("day", sort=True):
            rows.append({"method": method, "day": int(day), "blocks": int(len(g)),
                         "baseline_mae_w": metrics(g, "predicted_w")["mae_w"],
                         "corrected_mae_w": metrics(g, pred_col)["mae_w"],
                         "baseline_p90_abs_error_w": metrics(g, "predicted_w")["p90_abs_error_w"],
                         "corrected_p90_abs_error_w": metrics(g, pred_col)["p90_abs_error_w"],
                         "baseline_bias_w": metrics(g, "predicted_w")["bias_w"],
                         "corrected_bias_w": metrics(g, pred_col)["bias_w"]})
    perday = pd.DataFrame(rows)
    summary = []
    for method, g in perday.groupby("method", sort=False):
        full = oof.copy()
        baseline = metrics(full, "predicted_w")
        corrected = metrics(full, f"{method}_prediction_w")
        pred_col = f"{method}_prediction_w"
        interval_coverage = None
        interval_width = None
        if method in {"gpr_rbf_noise60", "gpr_rbf_noise100"}:
            sd = full[f"{method}_predictive_sd_w"].to_numpy(float)
            residual = full.residual_w.to_numpy(float) - full[f"{method}_correction_w"].to_numpy(float)
            interval_coverage = float(np.mean(np.abs(residual) <= 1.644854 * sd))
            interval_width = float(np.mean(2.0 * 1.644854 * sd))
        summary.append({"method": method, "pooled_baseline_mae_w": baseline["mae_w"],
                        "pooled_corrected_mae_w": corrected["mae_w"],
                        "pooled_mae_improvement_pct": 100 * (baseline["mae_w"] - corrected["mae_w"]) / baseline["mae_w"],
                        "macro_baseline_day_mae_w": float(g.baseline_mae_w.mean()),
                        "macro_corrected_day_mae_w": float(g.corrected_mae_w.mean()),
                        "days_won": int((g.corrected_mae_w < g.baseline_mae_w).sum()),
                        "p90_after_w": corrected["p90_abs_error_w"], "bias_after_w": corrected["bias_w"],
                        "nominal90_coverage": interval_coverage, "mean90_width_w": interval_width})
    OUT.write_text(oof.to_csv(index=False), encoding="utf-8-sig")
    perday.to_csv(ROOT / "reports/residual_crossday_by_day.csv", index=False, encoding="utf-8-sig")
    payload = {"method": "outer leave-one-day-out; inner training-day residual targets cross-fitted using models excluding both outer test day and residual-label day",
               "days": clean_days, "day6_used": False, "correction_cap_w": CAP_W,
               "target": "5-minute mean HV load residual against the existing out-of-day physics model",
               "feature_set": FEATURES,
               "route_lookup": "10 km route bins with median residual, requires >=2 distinct training days, shrunk by n_days/(n_days+2); course-specific diagnostic only",
               "pooled_baseline": metrics(oof, "predicted_w"), "per_method": summary,
               "per_day": perday.to_dict(orient="records"), "production_adopted": False,
               "interpretation": "One six-day race cannot support a claim of maximal model performance or transfer to BWSC2027. These models are diagnostics; no cross-day correction is deployed."}
    OUT_SUMMARY.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    lines = ["# Cross-day residual-model evaluation", "",
             "Residual corrections trained across days were tested in outer leave-one-day-out folds. Within each fold, every residual label for a training day was generated from a physics model excluding both that day and the outer test day. Day 6 was not used.",
             "", "## Results", "",
             "| Method | pooled MAE after (W) | pooled change (%) | macro daily MAE (W) | day wins / 5 | P90 after (W) | 90% interval coverage* |",
             "|---|---:|---:|---:|---:|---:|---:|"]
    for r in summary:
        cov = "—" if r["nominal90_coverage"] is None else f"{100*r['nominal90_coverage']:.1f}%"
        lines.append(f"| {r['method']} | {r['pooled_corrected_mae_w']:.1f} | {r['pooled_mae_improvement_pct']:+.1f} | {r['macro_corrected_day_mae_w']:.1f} | {r['days_won']}/5 | {r['p90_after_w']:.1f} | {cov} |")
    route_summary = oof.assign(route_bin=(oof.distance_m // 10000).astype(int)).groupby("day").distance_m.agg(["min", "max"])
    lines += ["", "The fixed physical baseline is included as the zero-correction reference in the CSV. Ridge fits use only speed, reconstructed relative air speed, route grade, ambient temperature and air density, with equal total weight per training day. The fixed RBF Gaussian-process candidates use those same five inputs and day-scaled observation noise; their nominal 90% intervals are reported as diagnostics, not guaranteed coverage. The distance-bin method is a 2025-course memorization diagnostic and cannot transfer to a different route.",
              "", "Day-specific distance ranges in the eligible data are: " + "; ".join(f"Day {day}: {row['min']/1000:.0f}–{row['max']/1000:.0f} km" for day, row in route_summary.iterrows()) + ". The ranges do not overlap in these blocks, explaining why a 10 km location lookup has no repeated-day evidence and cannot be trained from this race log.",
              "", "*For the Gaussian-process candidates, coverage is measured against the held-out residuals across five outer folds. The estimated intervals omit day-level distribution shift and cannot be treated as calibrated MPC safety bounds.",
              "", "No cross-day model is adopted. Training-fold residual labels come from three-day physical fits while the outer predictor uses four-day fits, so this deliberately leakage-safe design is conservative but not perfectly identical in base-model training size. Five independent day folds are too few to tune flexible models reliably.",
              "", "Outputs: `residual_crossday_oof.csv`, `residual_crossday_by_day.csv`, `residual_crossday_summary.json`.", ""]
    OUT_REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"baseline": payload["pooled_baseline"], "methods": summary,
                      "by_day": perday.to_dict(orient="records"), "outputs": [str(OUT), str(OUT_SUMMARY), str(OUT_REPORT)]},
                     ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
